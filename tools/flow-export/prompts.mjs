/**
 * Veo 3.1 prompt templates, one per character, for 8-second clips in Google
 * Flow. The character block is fixed and built only from metadata.json; the
 * scene block is the part a writer fills in per clip.
 */

/**
 * The name the prompt calls the character by. The canonical name is Persian;
 * an English prompt reads better with a Latin one, and the slug is also what a
 * Flow character is called with (`@roozi`).
 */
export function callName(meta) {
  return meta.id[0].toUpperCase() + meta.id.slice(1)
}

/** The fixed description: identical in every clip, so the model sees one character. */
export function characterBlock(meta) {
  const p = meta.proportions
  const lines = [
    `${callName(meta)} (${meta.name}): ${meta.description}`,
    `Visible features: ${meta.features.join('; ')}.`,
  ]
  if (meta.clothing.length) lines.push(`Clothing: ${meta.clothing.join('; ')}.`)
  if (meta.accessories.length) lines.push(`Accessories: ${meta.accessories.join('; ')}.`)
  lines.push(`Colours: ${meta.colorWords} (main colours by area: ${meta.colors.dominant.slice(0, 5).map((c) => c.hex).join(', ')}).`)
  const shape = [`about ${p.heightToWidth} times as tall as it is wide`]
  if (p.headShareOfHeight != null) shape.push(`the head, with its ears, hair or crest, takes up about the top ${Math.round(p.headShareOfHeight * 100)}% of its height`)
  lines.push(`Proportions: ${shape.join('; ')}; chunky, rounded, child-friendly shapes.`)
  lines.push(`Style: ${meta.rendering.style}.`)
  return lines.join('\n')
}

export function promptMarkdown(meta) {
  const block = characterBlock(meta)
  const flat = block.replace(/\n/g, ' ')
  const who = callName(meta)
  return `# ${meta.name} (\`${meta.id}\`): Veo 3.1 prompt template, 8 seconds

Generated by \`npm run export:flow\` from \`metadata.json\`. Edit the generator,
not this file: it is rewritten on every export.

## How to use it

1. In Google Flow, create a character from \`reference.png\` (and \`face.png\` as
   the second image), or add those two files as ingredients. See
   docs/flow-export.md for the details and the model limits.
2. Paste the **fixed character block** unchanged into every clip.
3. Fill in the **scene block**: one scene, one main action, one camera move.
4. Keep the continuity and negative lines.

## Fixed character block

Paste this unchanged into every clip.

\`\`\`text
${block}
\`\`\`

## Scene block (change per clip)

\`\`\`text
Scene: {{where we are, time of day, 1 sentence}}
Action: {{ONE main action ${who} performs in 8 seconds}}
Camera: {{one move: static wide shot | slow push-in | gentle pan left/right | slow orbit}}
Lighting and environment: {{soft daylight | warm indoor lamp light | ...; background details}}
Sound: {{ambient sound; dialogue only if wanted}}
\`\`\`

## Continuity

\`\`\`text
Continuity: keep ${who} identical to the reference images in every frame: same silhouette, same proportions, same colours, same ${meta.features.slice(0, 2).join(' and ')}. ${who} stays the same size relative to the frame unless the camera moves. Keep the illustrated cartoon look of the references; do not switch to a realistic, photographic or 3D-plastic render.
\`\`\`

## Negative constraints

\`\`\`text
Avoid: redesigning or restyling ${who}; changing colours, markings, eye colour or proportions; adding clothing, accessories, logos or props that are not in the reference${meta.clothing.length ? '' : ' (the character wears no clothing)'}; ${absentParts(meta)}extra limbs, extra eyes or a second copy of the character; text, captions, subtitles, watermarks or UI on screen.
\`\`\`

## Assembled example

\`\`\`text
${flat}
Scene: a sunny park lawn in the morning.
Action: ${exampleAction(meta)}
Camera: static wide shot at the character's eye level.
Lighting and environment: soft natural daylight, gentle shadows, green grass and blurred trees behind.
Sound: birdsong and a light breeze, no dialogue.
Continuity: keep ${who} identical to the reference images in every frame; keep the illustrated cartoon look.
Avoid: redesigning or restyling the character, changed colours or proportions, added clothing or accessories, text, captions or watermarks.
\`\`\`

## Known limits of the references

${meta.limitations.map((l) => `- ${l}`).join('\n')}
`
}

/** What the drawing does not have, so the video model is told not to add it. */
function absentParts(meta) {
  const s = meta.structure
  const missing = []
  if (!s.hasArms) missing.push('arms or hands')
  if (!s.hasLegLayers && meta.id === 'ava') missing.push('visible legs or feet below the dress')
  return missing.length ? `adding ${missing.join(' or ')} (the character has none); ` : ''
}

/** A gait the character actually has, so the example never asks for an impossible motion. */
function exampleAction(meta) {
  const g = meta.structure.gaits
  const who = callName(meta)
  if (g.includes('walk')) return `${who} walks slowly from left to right across the lawn, then stops and smiles at the camera.`
  if (g.includes('roll')) return `${who} rolls slowly from left to right across the path, then stops and smiles at the camera.`
  return `${who} looks around the lawn with curiosity, then turns to the camera and smiles.`
}
